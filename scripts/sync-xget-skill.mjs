import { chmod, copyFile, cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { CATALOG_VERSION, RELEASE_VERSION, SCHEMA_VERSION } from '../src/contracts/version.js';

const argumentsList = process.argv.slice(2);
if (argumentsList.length !== 2 || argumentsList[0] !== '--skill-dir') {
  process.stderr.write(
    'Usage: node scripts/sync-xget-skill.mjs --skill-dir /path/to/skills/xget\n'
  );
  process.exit(2);
}

const skillDirectory = resolve(argumentsList[1]);
const skillSource = await readFile(resolve(skillDirectory, 'SKILL.md'), 'utf8');
if (!/^name:\s*xget\s*$/m.test(skillSource)) {
  throw new Error('Target must be an existing skill with name: xget.');
}

// Rebuild from the authoritative contract before creating a distributable snapshot.
await import('./build-cli.mjs');
const cliDirectory = fileURLToPath(new URL('../packages/cli/', import.meta.url));
const scriptsDirectory = resolve(skillDirectory, 'scripts');
const bundleDirectory = resolve(scriptsDirectory, 'xget-cli');
await mkdir(scriptsDirectory, { recursive: true });
await rm(bundleDirectory, { recursive: true, force: true });
await mkdir(bundleDirectory, { recursive: true });
for (const directory of ['bin', 'lib', 'shared']) {
  await cp(resolve(cliDirectory, directory), resolve(bundleDirectory, directory), {
    recursive: true
  });
}
for (const file of ['LICENSE', 'README.md']) {
  await copyFile(resolve(cliDirectory, file), resolve(bundleDirectory, file));
}
const packageJson = JSON.parse(await readFile(resolve(cliDirectory, 'package.json'), 'utf8'));
// A distributed Skill snapshot is runnable as-is and has no repository build hooks.
delete packageJson.scripts;
await writeFile(
  resolve(bundleDirectory, 'package.json'),
  `${JSON.stringify(packageJson, null, 2)}\n`
);
await writeFile(
  resolve(bundleDirectory, 'provenance.json'),
  `${JSON.stringify(
    {
      source: 'https://github.com/xixu-me/Xget',
      directory: 'packages/cli',
      generator: 'scripts/sync-xget-skill.mjs',
      cliVersion: RELEASE_VERSION,
      schemaVersion: SCHEMA_VERSION,
      catalogVersion: CATALOG_VERSION
    },
    null,
    2
  )}\n`
);
const wrapper = resolve(scriptsDirectory, 'xget.mjs');
await writeFile(
  wrapper,
  `#!/usr/bin/env node\n// Generated by Xget scripts/sync-xget-skill.mjs. Do not edit.\nimport { runCli } from './xget-cli/lib/cli.js';\n\nprocess.exitCode = await runCli(process.argv.slice(2));\n`
);
await chmod(wrapper, 0o755);
process.stdout.write(`Synced Xget CLI ${RELEASE_VERSION} to ${skillDirectory}\n`);
